using UnityEngine;

// 방향별 벽 프리팹(골목 구성) 루트 오브젝트에 붙이는 마커 컴포넌트입니다.
//
// [배경]
// openWallPrefab(뚫린 방향에 쓰는 벽 프리팹)은 이제 "벽 하나 = 통째로 켜지고 꺼지는
// 오브젝트"가 아닙니다. 빌딩/화분/자판기 같은 배경 오브젝트는 항상 고정으로 존재하고,
// 그 사이에 낀 "바리케이드"만 방 클리어 여부에 따라 나타났다 사라졌다 합니다
// (골목처럼 보이게 구성 + 바리케이드로 통행을 막는 방식).
//
// LevelBuilder가 openWallPrefab을 인스턴스화할 때 이 컴포넌트를 찾아서, barricade
// 필드에 연결된 오브젝트만 RoomController의 Lock/UnlockGates 대상으로 등록합니다.
// 나머지 배경 오브젝트(빌딩, 소품 등)는 이 컴포넌트와 무관하게 항상 그대로 존재합니다.
//
// [사용 방법]
// 1. 골목 구조로 조립한 openWallPrefab용 프리팹의 최상위(루트) 오브젝트에 이 컴포넌트를 추가합니다.
// 2. Barricade 필드에, 방이 클리어되기 전까지만 보여야 할 바리케이드 오브젝트를 연결합니다.
// 3. 완전히 막힌 벽(closedWallPrefab에 쓸 프리팹, 예: 앵커 없는 방향의 3빌딩 구성)에는
//    이 컴포넌트가 필요 없습니다 - 앵커 자체가 없는 방향이라 바리케이드 개념이 없습니다.
//
// [주의]
// barricade 오브젝트는 총알도 막아야 하므로 Tag를 "Wall"로, 콜라이더는 트리거가 아닌
// 상태로 설정해주세요 (배경 오브젝트들과 동일한 규칙입니다).
//
// [특수방 부모용 벽 - 특수방 잠금 바리케이드]
// 일반방(또는 시작방)에서 수류탄/해킹툴 특수방을 향한 벽에는 바리케이드가 2단으로 섭니다.
// - barricade(전투 바리케이드): 위와 같음 - 부모 방 전투가 끝나면 사라짐
// - specialLockBarricade(특수방 잠금 바리케이드): 수류탄/해킹툴로 파괴되기 전까지 남아 있음(전투와 무관)
// specialLockBarricade는 이 벽이 "잠긴 특수방을 향한 부모 방 쪽 벽"일 때만 켜지고, 그 외(일반 연결, 그냥 진입/
// 체력 소모 특수방, 특수방 자신의 벽 등)에는 LevelBuilder가 자동으로 끕니다. 비워두면 LevelBuilder가 임시 큐브를
// 대신 세웁니다.
// 배치 규칙(중요): 잠금 바리케이드는 전투 바리케이드보다 "방 안쪽"(부모 방 중심 쪽)에 붙여 두고, 콜라이더가 칸 경계선을
// 넘어가지 않게 해주세요. 플레이어가 경계선을 넘는 순간 옆 방(특수방)으로 들어간 것으로 처리되어, 경계선 너머에 있는
// 잠금 바리케이드는 플레이어를 막지 못합니다. barricade의 자식으로 넣지 말고(전투 바리케이드와 함께 꺼짐) 형제로
// 두세요. Tag "Wall", 트리거가 아닌 콜라이더, Renderer가 필요합니다(barricade와 같은 규칙).
public class WallSidePrefab : MonoBehaviour
{
    [Tooltip("이 방향이 다른 방과 연결되어 있을 때만 등장하는 바리케이드입니다. " +
             "방이 클리어되지 않은 동안은 활성화되어 통행을 막고, 클리어되면(또는 " +
             "애초에 클리어 조건이 없는 방이면) 비활성화되어 플레이어가 지나갈 수 있게 됩니다.")]
    public GameObject barricade;

    [Tooltip("특수방 부모용 벽에서만 쓰는 2단째 바리케이드입니다(수류탄/해킹툴 특수방 잠금). 전투와 무관하게 수류탄/해킹툴로 " +
             "파괴되기 전까지 남아 있습니다. 일반 열린 벽 프리팹에서는 비워두면 됩니다. Barricade와 다른 오브젝트여야 하고, " +
             "Barricade의 자식이면 안 되며, 전투 바리케이드보다 방 안쪽에 둬야 합니다(위 주석 참고).")]
    public GameObject specialLockBarricade;
}